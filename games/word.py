# ==========================================
# ساخت کلمه مخفی
# ==========================================

def hide_word(word, level):

    chars = list(word)


    # فاصله ها حذف نشوند
    indexes = [
        i for i, c in enumerate(chars)
        if c != " "
    ]


    if level == "easy":

        remove_percent = 0.25


    elif level == "medium":

        remove_percent = 0.45


    else:

        remove_percent = 0.65



    remove_count = max(
        2,
        int(len(indexes) * remove_percent)
    )


    hidden_indexes = random.sample(
        indexes,
        remove_count
    )


    for i in hidden_indexes:

        chars[i] = "_"



    return "".join(chars)



# ==========================================
# ساخت بازی
# ==========================================

def create_game(level):

    category = random.choice(
        list(CATEGORIES.keys())
    )


    word = random.choice(
        CATEGORIES[category]
    )


    hidden = hide_word(
        word,
        level
    )


    return {

        "word": word,

        "hidden": hidden,

        "level": level,

        "category": category

    }

# ==========================================
# بررسی جواب
# ==========================================

def check(game, answer):


    if not answer:

        return False


    # حذف فاصله‌های اضافی

    answer = answer.strip()


    correct = game["word"].strip()


    # مقایسه مستقیم

    if answer == correct:

        return True



    # مقایسه بدون فاصله

    answer_clean = answer.replace(
        " ",
        ""
    )

    correct_clean = correct.replace(
        " ",
        ""
    )


    if answer_clean == correct_clean:

        return True



    return False



# ==========================================
# تست تعداد کلمات
# ==========================================

def categories_count():

    total = 0

    for category in CATEGORIES.values():

        total += len(category)


    return total